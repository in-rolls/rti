source("scripts/00_config.R")
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2L) stop("Usage: Rscript scripts/draw_batch.R CONFIG OUTPUT_DIRECTORY")
if (dir.exists(args[2])) stop("Output directory already exists; issued batches cannot be overwritten")
release <- build_release()
config <- yaml::read_yaml(args[1])
issued <- read_issued_assignments()
if (config$batch_id %in% issued$batch_id) stop("Batch ID already issued")
batch <- draw_batch(release$authorities, config, issued)
write_csv_text(batch$assignments, file.path(args[2], "assignments.csv"))
batch$metadata$assignments_sha256 <- hash_file(file.path(args[2], "assignments.csv"))
jsonlite::write_json(batch$metadata, file.path(args[2], "metadata.json"), auto_unbox = TRUE, pretty = TRUE)
write_worklists(batch$assignments, file.path(args[2], "worklists"))
